#!/usr/bin/env node
/**
 * Writes the pages of the site that come from the repository itself, so the site never says
 * something the repository does not:
 *
 * - docs/reference/  docs/*.md (architecture, runner setup, workstation, API, MCP, security, mutation);
 * - docs/project/    VERSIONING.md, ROADMAP.md, CHANGELOG.md, CONTRIBUTING.md, SECURITY.md,
 *                    CODE_OF_CONDUCT.md.
 *
 * The rest of docs/ (introduction, getting started, features, scenarios, operations, caveats,
 * FAQ) is written in website/docs/. Links between synced files become links between pages;
 * links to a page written under website/docs/ become links to it; links to anything else in
 * the repository point to GitHub. Both output folders are rewritten on every run and are not
 * committed.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(site, "..");
const docs = join(site, "docs");
const REPOSITORY = "https://github.com/izaccavalheiro/testor";

/** Repository path → [page under docs/, sidebar label, position]. */
const FILES = {
  "docs/architecture.md": ["reference/architecture.md", "Architecture", 1],
  "docs/runner-setup.md": ["reference/runner-setup.md", "Runner setup", 2],
  "docs/workstation.md": ["reference/workstation.md", "Workstation and projects", 3],
  "docs/api.md": ["reference/api.md", "HTTP and SSE API", 4],
  "docs/mcp.md": ["reference/mcp.md", "MCP server", 5],
  "docs/security.md": ["reference/security.md", "Security model", 6],
  "docs/attestation.md": ["reference/attestation.md", "Run attestations", 7],
  "docs/jobs.md": ["reference/jobs.md", "Jobs and agents", 8],
  "docs/mutation.md": ["reference/mutation.md", "Mutation testing", 9],
  "docs/result-formats.md": ["reference/result-formats.md", "Result formats", 10],
  "docs/heavy-jobs.md": ["reference/heavy-jobs.md", "Heavy jobs", 11],
  "docs/queues.md": ["reference/queues.md", "Job queues on a broker", 12],
  "docs/storage.md": ["reference/storage.md", "Runs in object storage", 13],
  "VERSIONING.md": ["project/versioning.md", "Versioning and releases", 1],
  "ROADMAP.md": ["project/roadmap.md", "Roadmap", 2],
  "CHANGELOG.md": ["project/changelog.md", "Changelog", 3],
  "CONTRIBUTING.md": ["project/contributing.md", "Contributing", 4],
  "SECURITY.md": ["project/security-policy.md", "Security policy", 5],
  "CODE_OF_CONDUCT.md": ["project/code-of-conduct.md", "Code of conduct", 6],
};

const CATEGORIES = {
  reference: ["Reference", 8, "The reference documentation, from docs/ in the repository."],
  project: ["Project", 9, "How testor is versioned, released and developed, and where it is going."],
};

/** The page (relative to docs/) a repository path is, if it is one. */
function pageFor(repoPath) {
  if (FILES[repoPath]) return FILES[repoPath][0];
  const written = /^website\/docs\/(.+\.mdx?)$/.exec(repoPath);
  return written && existsSync(join(root, repoPath)) ? written[1] : undefined;
}

/** Rewrites the Markdown links of a repository file for its page. Fenced code is left alone. */
function rewrite(text, repoPath, page) {
  const from = posix.dirname(repoPath);
  const pageDir = posix.dirname(page);
  let fenced = false;
  return text
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
      if (fenced) return line;
      return line.replace(/\]\(([^)\s]+)\)/g, (whole, target) => {
        if (/^([a-z]+:|#|\/)/i.test(target)) return whole;
        const [path, anchor] = target.split("#");
        const resolved = posix.normalize(posix.join(from, path)).replace(/\/$/, "");
        const to = pageFor(resolved);
        const hash = anchor ? `#${anchor}` : "";
        if (to) return `](${posix.relative(pageDir, to) || posix.basename(to)}${hash})`;
        const kind = existsSync(join(root, resolved)) && statSync(join(root, resolved)).isDirectory() ? "tree" : "blob";
        return `](${REPOSITORY}/${kind}/main/${resolved}${hash})`;
      });
    })
    .join("\n");
}

for (const dir of Object.keys(CATEGORIES)) rmSync(join(docs, dir), { recursive: true, force: true });

for (const [dir, [label, position, description]] of Object.entries(CATEGORIES)) {
  mkdirSync(join(docs, dir), { recursive: true });
  const category = { label, position, link: { type: "generated-index", description } };
  writeFileSync(join(docs, dir, "_category_.json"), JSON.stringify(category, null, 2) + "\n");
}

for (const [repoPath, [page, label, position]] of Object.entries(FILES)) {
  const source = readFileSync(join(root, repoPath), "utf8");
  const front = [
    "---",
    `sidebar_label: ${JSON.stringify(label)}`,
    `sidebar_position: ${position}`,
    `custom_edit_url: ${REPOSITORY}/edit/main/${repoPath}`,
    "---",
    "",
    `<!-- Generated by website/scripts/sync.mjs from ${repoPath}: edit that file instead. -->`,
    "",
  ].join("\n");
  writeFileSync(join(docs, page), front + rewrite(source, repoPath, page));
}

console.log(`sync: ${Object.keys(FILES).length} pages from the repository`);
